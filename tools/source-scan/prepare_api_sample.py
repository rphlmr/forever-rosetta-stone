#!/usr/bin/env python3
"""Prepare a catalog-sampled copy of the local tooltip-check probe; never install or start it.

The copy adds `api-sample.lua`, which extends the `/frsverify api` inventory with a deterministic
sample of owned catalog IDs per kind and every owned GlobalStrings key. The sample is a test
inventory, never a runtime allowlist.
"""

import argparse
import hashlib
import json
import shutil
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
sys.path.insert(0, str(ROOT))
from tools.catalogs.catalog_storage import dump_json

PROBE = Path(__file__).resolve().parent / 'rosetta-tooltip-check'
# Catalog directory -> `/frsverify api` kind.
KINDS = {'items': 'item', 'spells': 'spell', 'quests': 'quest', 'maps': 'map', 'areas': 'area', 'factions': 'faction'}
SAMPLE_FILE = 'api-sample.lua'


def catalog_ids(kind, root=ROOT):
    return sorted(int(path.stem) for path in (root / 'catalogs' / kind).glob('*.json') if path.stem.isdigit())


def sample(ids, size, seed, kind):
    """Pick a stable pseudo-random subset; the same catalog and seed give the same IDs."""
    ranked = sorted(ids, key=lambda value: hashlib.sha256(f'{seed}:{kind}:{value}'.encode()).hexdigest())
    return sorted(ranked[:size])


def global_keys(root=ROOT):
    keys = set()
    for path in (root / 'catalogs/globalstrings').glob('*.json'):
        if path.stem.isdigit():
            keys.add(json.loads(path.read_text(encoding='utf-8'))['key'])
    return sorted(keys)


def lua_list(values, quote=False, per_line=12):
    items = [f'"{value}"' if quote else str(value) for value in values]
    lines = ['    ' + ', '.join(items[index:index + per_line]) + ',' for index in range(0, len(items), per_line)]
    return '{\n' + '\n'.join(lines) + '\n}' if items else '{}'


def render(selection, keys, sample, timeout):
    parts = [
        'local _, Probe = ...',
        '-- Generated by tools/source-scan/prepare_api_sample.py. Test inventory, not a runtime allowlist.',
        'local api = Probe.cases.api',
        f'api.loadTimeout = {timeout}',
        'api.sample = {' + ', '.join(f'{key} = {json.dumps(value)}' for key, value in sorted(sample.items())) + '}',
        'local function Add(list, values)',
        '    local seen = {}',
        '    for _, value in ipairs(list) do seen[value] = true end',
        '    for _, value in ipairs(values) do',
        '        if not seen[value] then list[#list + 1] = value; seen[value] = true end',
        '    end',
        'end',
    ]
    for kind in sorted(selection):
        parts.append(f'api.ids.{kind} = api.ids.{kind} or {{}}')
        parts.append(f'Add(api.ids.{kind}, {lua_list(selection[kind])})')
    parts.append(f'Add(api.globals, {lua_list(keys, quote=True, per_line=4)})')
    return '\n'.join(parts) + '\n'


def write_probe_copy(output, selection, keys, sample, timeout, counts):
    """Copy the probe with `api-sample.lua` after `cases.lua`, and write `sample.json` beside it."""
    addon = output / PROBE.name
    shutil.copytree(PROBE, addon, ignore=shutil.ignore_patterns('README.md'))
    (addon / SAMPLE_FILE).write_text(render(selection, keys, sample, timeout), encoding='utf-8')
    toc = addon / 'rosetta-tooltip-check.toc'
    lines = toc.read_text(encoding='utf-8').splitlines()
    lines.insert(lines.index('cases.lua') + 1, SAMPLE_FILE)
    toc.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    manifest = dict(sample, loadTimeout=timeout, counts=counts, ids=selection)
    (output / 'sample.json').write_text(dump_json(manifest), encoding='utf-8')


def prepare(output, size, seed, timeout, root=ROOT):
    selection, counts = {}, {}
    for directory, kind in KINDS.items():
        ids = catalog_ids(directory, root)
        selection[kind] = sample(ids, size, seed, kind)
        counts[kind] = {'catalog': len(ids), 'sampled': len(selection[kind])}
    keys = global_keys(root)
    counts['globals'] = {'catalog': len(keys), 'sampled': len(keys)}
    write_probe_copy(output, selection, keys, {'seed': seed, 'perKind': size}, timeout, counts)
    return counts


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument('--output', required=True, type=Path, help='New directory under datasources/imports/')
    parser.add_argument('--per-kind', type=int, default=300, help='IDs sampled per catalog kind (default 300)')
    parser.add_argument('--seed', default='frs-api-sample-1', help='Sampling seed; change it for a different sample')
    parser.add_argument('--load-timeout', type=int, default=120, help='Seconds to wait for the client cache')
    args = parser.parse_args()
    output = args.output.resolve()
    if not output.is_relative_to((ROOT / 'datasources/imports').resolve()):
        parser.error('--output must be under datasources/imports/')
    if output.exists():
        parser.error(f'{output} already exists; choose a new directory')
    if args.per_kind <= 0 or args.load_timeout <= 0:
        parser.error('--per-kind and --load-timeout must be positive')
    output.mkdir(parents=True)
    counts = prepare(output, args.per_kind, args.seed, args.load_timeout)
    for kind, count in counts.items():
        print(f'{kind}: {count["sampled"]} / {count["catalog"]}')
    print(f'Probe copy: {output / PROBE.name}')


if __name__ == '__main__':
    main()
