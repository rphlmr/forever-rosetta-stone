"""Generate load-on-demand addons containing compressed database pages."""

import json
import re


def pack_directory(root, name):
    """Map an installed addon identity to its compact repository directory."""
    if name == 'ForeverRosettaStone_Rules':
        return root / 'Rules'
    match = re.fullmatch(r'ForeverRosettaStone_Data_([a-z]{2}[A-Z]{2})', name)
    if not match:
        raise ValueError('Invalid database pack name: ' + name)
    return root / match[1]


def write_pack(root, name, version, pages, interface):
    """Keep payload strings in Lua files so unloaded addons retain only their small TOCs."""
    directory = pack_directory(root, name)
    directory.mkdir(parents=True, exist_ok=True)
    manifest = (
        f'## Interface: {interface}\n'
        f'## Title: Forever Rosetta Stone: {name.removeprefix("ForeverRosettaStone_")}\n'
        '## LoadOnDemand: 1\n'
        '## Dependencies: ForeverRosettaStone\n'
        f'## X-Rosetta-Catalog: {version}\n'
        '\ndata.lua\n'
    )
    (directory / (name + '.toc')).write_text(manifest, encoding='utf-8')
    entries = ''.join(
        f'    [{json.dumps(key)}] = {json.dumps(value.decode("ascii"))},\n'
        for key, value in sorted(pages.items())
    )
    source = (
        '-- Generated by tools/build/build-lua-database.py. Do not edit.\n'
        f'ForeverRosettaStoneDB:RegisterStorage({json.dumps(name)}, {json.dumps(version)}, {{\n'
        + entries + '})\n'
    )
    (directory / 'data.lua').write_text(source, encoding='ascii')
