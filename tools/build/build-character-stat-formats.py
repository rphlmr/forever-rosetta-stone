"""Build character-stat translations from retained, build-matched GlobalStrings exports."""

import argparse
import csv
import json
import re
from pathlib import Path

import sys
sys.path.insert(0, str(Path(__file__).resolve().parents[2]))
from tools.build.runtime_catalog import decode_client_escapes

ROOT = Path(__file__).resolve().parents[2]
COMMIT = '9dc84f0d3bbae1768ac3405b3716000bd93eda06'


def read_strings(path):
    with path.open(encoding='utf-8', newline='') as stream:
        return {row['BaseTag']: decode_client_escapes(row['TagText_lang']) for row in csv.DictReader(stream)}


def build(source_dir, strings_dir):
    manifest = json.loads((strings_dir / 'manifest.json').read_text())
    client_build = manifest['build']
    english = read_strings(strings_dir / f'GlobalStrings.{client_build}.enUS.csv')
    source = (source_dir / 'rosetta-paper-doll.lua').read_text().splitlines()
    source = '\n'.join(source[610:1506] + source[2281:2390])
    source += (source_dir / 'rosetta-paper-doll-stats.lua').read_text()
    keys = set(re.findall(r'\b[A-Z][A-Z0-9_]+\b', source)) & english.keys()
    classes = 'DEFAULT WARRIOR PALADIN HUNTER ROGUE PRIEST SHAMAN MAGE WARLOCK DRUID DEATHKNIGHT MONK'.split()

    for key in english:
        if re.fullmatch(r'(?:RESISTANCE\d_NAME|RESISTANCE_TYPE\d|DAMAGE_SCHOOL\d|SPELL_STAT\d_NAME)', key):
            keys.add(key)

        if any(key.startswith(name + '_') for name in classes) and key.endswith('_TOOLTIP'):
            if any(stat in key for stat in ('STRENGTH', 'AGILITY', 'STAMINA', 'INTELLECT', 'SPIRIT', 'MELEE_ATTACK_POWER')):
                keys.add(key)

        if re.fullmatch(r'(?:CR_\w+_HIT_CAP_TOOLTIP|STAT_\w+_CRIT_BONUS|MELEE_ATTACK_POWER_PET_\w+_TOOLTIP)', key):
            keys.add(key)

    keys.update(key for key in (
        'HEALTH', 'MANA', 'RAGE', 'ENERGY', 'FOCUS', 'RUNIC_POWER', 'STAT_MANA_TOOLTIP', 'STAT_RAGE_TOOLTIP',
        'STAT_ENERGY_TOOLTIP', 'STAT_FOCUS_TOOLTIP', 'STAT_RUNIC_POWER_TOOLTIP', 'AXES', 'TWO_HANDED_AXES',
        'SWORDS', 'TWO_HANDED_SWORDS', 'MACES', 'TWO_HANDED_MACES', 'DAGGERS', 'STAVES', 'POLEARMS',
        'BOWS', 'GUNS', 'CROSSBOWS', 'WANDS', 'THROWN', 'UNARMED', 'FIST_WEAPONS', 'FERAL_COMBAT',
    ) if key in english)
    lines = [
        'local _, Addon = ...', '',
        f'-- Generated by tools/build/build-character-stat-formats.py; GlobalStrings {client_build}, UI {COMMIT}.',
        'Addon.characterStatFormats = {',
    ]

    for path in sorted(strings_dir.glob(f'GlobalStrings.{client_build}.*.csv')):
        locale = path.stem.rsplit('.', 1)[1]
        strings = read_strings(path)
        lines.append(f'    {locale} = {{')

        for key in sorted(keys):
            if strings.get(key):
                lines.append(f'        {key} = {json.dumps(strings[key], ensure_ascii=False)},')

        lines.append('    },')

    lines.extend(['}', ''])
    (ROOT / 'ForeverRosettaStone/tooltips/character-stat-formats.lua').write_text('\n'.join(lines))
    print(f'Generated {len(keys)} keyed character-stat formats')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source-dir', type=Path, required=True, help='Directory with the pinned Camelot PaperDoll Lua sources')
    parser.add_argument('--strings-dir', type=Path, required=True, help='Wago directory from datasources/imports/RUN/wago')
    args = parser.parse_args()
    build(args.source_dir, args.strings_dir)
