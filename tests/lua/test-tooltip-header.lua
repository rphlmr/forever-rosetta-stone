local Addon = ...
local checks = 0
local function equal(actual, expected, label)
    assert(actual == expected, label .. ": expected " .. tostring(expected) .. ", got " .. tostring(actual))
    checks = checks + 1
end
local source = Addon:CreateCompanionTooltip(nil, UIParent)
local translated = Addon:CreateCompanionTooltip(nil, UIParent)
source.accurateLines, translated.accurateLines = true, true
local label = Addon:GetTooltipTranslationLabel()
local function hasLabel(tip)
    for index = 1, tip:NumLines() do
        if tip:GetLeftLine(index):GetText() == label then return true end
    end
    return false
end
equal(Addon.preferences.translationHeader, true, "translation headers are enabled by default")
equal(Addon.settings.translationHeader:GetValue(), true, "native Settings exposes the default")
source:SetText("Native title")
translated:SetText("Translated title")
Addon:FillStackedTooltip(source, translated, "same-content")
equal(hasLabel(source), true, "stacked translations show the header by default")
Addon.settings.translationHeader:SetValue(false)
Addon:FillStackedTooltip(source, translated, "same-content")
equal(hasLabel(source), false, "disabling headers removes their text and icon from cached stacked content")
equal(source:GetLeftLine(1):GetText(), "Native title", "native title stays intact")
translated:ClearLines()
Addon:SetStandaloneTooltipTitle(translated, "Translated title")
equal(translated:GetLeftLine(1):GetText(), "Translated title", "standalone title becomes the first row without a header")
equal(hasLabel(translated), false, "standalone tooltips also hide the header")
Addon:LoadPreferences()
equal(Addon.preferences.translationHeader, false, "header opt-out survives preferences loading")
Addon.settings.translationHeader:SetValueToDefault()
equal(Addon.preferences.translationHeader, true, "native Defaults restores headers")
translated:ClearLines()
Addon:SetStandaloneTooltipTitle(translated, "Translated title")
equal(translated:GetLeftLine(2):GetText(), "Translated title", "standalone title follows the restored header")
equal(hasLabel(translated), true, "standalone header returns after restoring defaults")
Addon:ClearStackedTooltip(source)
Addon:ClearStackedTooltip(source, true)
source:ClearLines()
source:AddLine("Native title")
source:AddLine("Restricted native amount")
local nativeLine = source:GetLeftLine(2)
local originalGetText, reads = nativeLine.GetText, 0
nativeLine.GetText = function() reads = reads + 1; return { secret = true } end
translated:ClearLines()
translated:SetOwner(UIParent, "ANCHOR_NONE")
translated:SetText("Translated aura")
translated:Show()
Addon:FillStackedTooltip(source, translated, "restricted-native-row")
equal(translated:IsShown(), false, "stacked mode never leaves a second companion visible")
equal(reads, 0, "stacking does not need to read the original restricted rows")
equal(source:GetLeftLine(source:NumLines()):GetText(), "Translated aura", "translation is appended after restricted native content")
equal(source:GetLeftLine(1):GetText(), "Native title", "stacking preserves the native title")
nativeLine.GetText = originalGetText
Addon:ClearStackedTooltip(source)
source:Hide()
translated:Hide()

source:ClearLines()
source:SetSize(80, 30)
source:SetPadding(4, 7, 2, 1)
source:AddLine("Native item")
source:Show()
translated:ClearLines()
translated:AddDoubleLine("Translated item", "Value")
translated:Show()
local previousMode = Addon.preferences.tooltipMode
Addon:SetTooltipMode("stacked")
Addon:SetStackedTranslationFirst(true)
Addon:FillStackedTooltip(source, translated, "translation-first")
local saved = Addon.stackedTooltips[source]
local block = saved.block
equal(block:IsShown(), true, "translation-first block is visible inside the original tooltip")
equal(block:GetParent(), source, "the block follows the native tooltip")
equal(block.NineSlice:GetAlpha(), 0, "only the original tooltip draws its backdrop")
equal(block:GetLeftLine(1):GetText(), label, "translation-first shows the optional header")
equal(block:GetLeftLine(2):GetText(), "Translated item", "translation follows the header")
equal(block:GetRightLine(2):GetText(), "Value", "translation-first keeps the right column")
equal(source:NumLines(), 1, "translation-first keeps the native row count")
equal(source:GetLeftLine(1):GetText(), "Native item", "translation-first leaves native text intact")
equal(select(4, source:GetPadding()), 1 + block:GetHeight(), "top padding reserves room for the translated block")
equal(select(2, source:GetPadding()), 7, "native bottom padding is preserved")
Addon:RefreshStackedTranslationFirst(source, saved)
equal(select(4, source:GetPadding()), 1 + block:GetHeight(), "repeated layout does not accumulate padding")
local right, bottom, left, top = source:GetPadding()
source:SetPadding(right, bottom + 2, left, top)
Addon:RefreshStackedTranslationFirst(source, saved)
equal(select(4, source:GetPadding()), top, "changing bottom padding preserves the existing top reservation")
source:SetPadding(8, 9, 0, 3)
Addon:RefreshStackedTranslationFirst(source, saved)
equal(select(4, source:GetPadding()), 3 + block:GetHeight(), "native refresh can replace the base padding")
right, bottom, left, top = source:GetPadding()
source:SetPadding(right, bottom, left + 1, top)
Addon:ClearStackedTooltip(source, true)
equal(select(3, source:GetPadding()), left + 1, "cleanup preserves another addon's latest left padding")
equal(block:IsShown(), false, "native clear hides the translated block")
equal(select(4, source:GetPadding()), 3, "native clear restores the most recent base padding")
equal(select(2, source:GetPadding()), 9, "native clear restores the entire base padding")
Addon:SetStackedTranslationFirst(false)
Addon:SetTooltipMode(previousMode)
source:ClearPadding()
source:Hide()

source:ClearLines()
source:SetAlpha(0.7)
source:AddLine("Native tooltip")
source:Show()
Addon:SetTranslationOnly(true)
translated:ClearLines()
Addon:SetStandaloneTooltipTitle(translated, "Translated tooltip")
equal(translated:GetLeftLine(1):GetText(), "Translated tooltip", "translation-only suppresses the standalone header")
Addon:FillStackedTooltip(source, translated, "translation-only")
equal(source:GetAlpha(), 0, "translation-only hides only the original rendering")
equal(source:IsShown(), true, "the original frame remains live")
equal(translated:GetAlpha(), 0.7, "translation uses the original opacity")
local point, anchor, relative = translated:GetPoint(1)
equal(point, "TOPLEFT", "replacement uses its top-left corner")
equal(anchor, source, "replacement anchors to the original tooltip")
equal(relative, "TOPLEFT", "replacement uses the original top-left corner")
translated:Hide()
equal(source:GetAlpha(), 0.7, "hiding the replacement restores the original alpha")
Addon:ClearStackedTooltip(source, true)
source:SetPoint("TOPRIGHT", UIParent, "TOPRIGHT", 0, 0)
Addon:FillStackedTooltip(source, translated, "right-anchored-translation")
equal(select(1, translated:GetPoint(1)), "TOPRIGHT", "the original anchor edge controls where the replacement grows")
Addon:ClearStackedTooltip(source, true)
translated:ClearLines()
Addon:FillStackedTooltip(source, translated, "missing-translation")
equal(source:GetAlpha(), 0.7, "the original remains visible when no translation is available")
source:AddDoubleLine("Auction", "7 copper")
translated:AddLine("Translated item")
Addon:AppendTooltipExtraRows({ source = source, tip = translated, data = { lines = { { lineIndex = 1 } } } })
equal(translated:GetLeftLine(3):GetText(), "Auction", "extra item data is kept alongside the translation")
equal(translated:GetRightLine(3):GetText(), "7 copper", "extra tooltip rows preserve both columns")
local rule = source:CreateTexture()
local decoration = CreateFrame("Frame", nil, source)
decoration:EnableMouse(false)
decoration:CreateTexture():Show()
rule:Show()
Addon:FillStackedTooltip(source, translated, "decorated-rows")
equal(source:GetAlpha(), 0, "passive separators and their parent do not bring back the original text")
equal(translated:GetRightLine(3):GetText(), "7 copper", "decorated rows retain the addon's text")
local nestedButton = CreateFrame("Button", nil, decoration)
nestedButton:EnableMouse(true)
nestedButton:Show()
Addon:FillStackedTooltip(source, translated, "decorated-rows")
equal(source:GetAlpha(), 0.7, "a button in a passive holder keeps the original visible")
equal(Addon.stackedTooltips[source].block:GetLeftLine(1):GetText(), "Translated item",
    "widget fallback preserves the translated content")
nestedButton:Hide()
decoration:EnableMouse(true)
equal(Addon:HasLiveTooltipWidgets(source, translated), true, "interactive children require keeping the native tooltip")
Addon:ClearStackedTooltip(source, true)
decoration:Hide()
rule:Hide()
translated:ClearLines()
translated:AddLine("Translated item")
local widget = CreateFrame("Frame", nil, source)
widget:Show()
source.insertedFrames = { widget }
Addon:FillStackedTooltip(source, translated, "live-widget")
equal(source:GetAlpha(), 0.7, "a live addon widget keeps its native frame visible")
equal(widget:IsShown(), true, "the widget stays attached to its original tooltip")
equal(Addon.stackedTooltips[source].block:GetLeftLine(1):GetText(), "Translated item",
    "widget fallback still shows the translation first, without the translation header")
Addon:ClearStackedTooltip(source, true)
source.insertedFrames = nil
widget:Hide()
Addon:SetTranslationOnly(false)
equal(Addon:ShouldShowTranslationHeader(), true, "the stored header setting applies again")
source:Hide()

-- FontString getters can return restricted text even on an addon-owned companion.
-- Lua 5.1 cannot model secret strings, so verify that neither column reaches the target.
local restricted = { secret = true }
for index, columns in ipairs({
    { "Restricted amount", restricted },
    { restricted, "Readable amount" },
    { restricted, restricted },
}) do
    local native = Addon:CreateCompanionTooltip(nil, UIParent)
    native.accurateLines = true
    native:SetText("Native title")
    translated:ClearLines()
    translated:AddLine("Translated title")
    translated:AddDoubleLine("Temporary label", "Temporary amount")
    translated:GetLeftLine(2).GetText = function() return columns[1] end
    translated:GetRightLine(2).GetText = function() return columns[2] end
    translated:AddDoubleLine("Damage", "4 - 7")
    translated:Show()
    local ok = Addon:Run("stack restricted companion text", function()
        Addon:FillStackedTooltip(native, translated, "restricted-companion-" .. index)
    end)
    equal(ok, true, "restricted companion text does not fail the safety wrapper")
    equal(Addon.lifecycle, "ready", "restricted companion text keeps the addon running")
    equal(native:NumLines(), 5, "restricted rows are omitted without leaving partial columns")
    equal(native:GetLeftLine(1):GetText(), "Native title", "restricted rows leave native content intact")
    equal(native:GetLeftLine(4):GetText(), "Translated title", "readable translated rows are retained")
    equal(native:GetRightLine(5):GetText(), "4 - 7", "readable double-column rows are retained")
    equal(translated:IsShown(), false, "restricted companion text still hides the companion")
    equal(Addon.tooltipRendering, nil, "restricted companion text leaves rendering state clear")
    translated:GetLeftLine(2).GetText = originalGetText
    translated:GetRightLine(2).GetText = originalGetText
    Addon:ClearStackedTooltip(native)
    native:Hide()
end
return checks
